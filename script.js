var isAdmin=/[?&]admin\b/i.test(location.search);

function saveUserStories(){localStorage.setItem('ls:stories',JSON.stringify(userStories))}
function saveProgress(id,i){progress[id]=i;localStorage.setItem('ls:progress',JSON.stringify(progress))}
function getProgress(id){return progress[id]||-1}
function isDefault(id){return DEFAULT_STORIES.some(function(s){return s.id===id})}

