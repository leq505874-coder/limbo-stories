function parseHash(){
  var h=location.hash.replace(/^#/,'');
  if(!h)return{page:'home'};
  if(h==='tos')return{page:'tos'};
  var p=h.split('/');
  if(p[0]==='story'&&p[1])return{page:'story',storyId:p[1]};
  if(p[0]==='read'&&p[1]&&p[2]!==undefined)return{page:'read',storyId:p[1],chIdx:parseInt(p[2])};
  return{page:'home'};
}

window.addEventListener('hashchange',render);

// ============ RENDER ============
function render(){
  document.querySelectorAll('.controls,.progress').forEach(function(n){n.remove()});
  var route=parseHash();
  var main=document.getElementById('main');
  var title=document.getElementById('pageTitle');
  main.innerHTML='';
  window.scrollTo(0,0);

  if(route.page==='home'){
    title.className='';
    title.innerHTML='Limbo<br>Stories';
    renderHome(main);
  } else if(route.page==='tos'){
    title.className='small';
    title.textContent='Điều khoản sử dụng';
    renderTOS(main);
  } else if(route.page==='story'){
    var s=STORIES.filter(function(x){return x.id===route.storyId})[0];
    if(!s){location.hash='';return}
    title.className='small';
    title.textContent=s.title;
    renderStory(main,s);
  } else if(route.page==='read'){
    var s2=STORIES.filter(function(x){return x.id===route.storyId})[0];
    if(!s2||!s2.chapters[route.chIdx]){location.hash='';return}
    title.className='small';
    title.textContent=s2.title;
    renderRead(main,s2,route.chIdx);
  }
}

