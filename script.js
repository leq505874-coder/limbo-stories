function openAddStory(){
  var bg=el('div',{className:'modal-bg show'});
  var modal=el('div',{className:'modal'});
  modal.appendChild(el('h3',{textContent:'Thêm truyện mới'}));

  var tIn=el('input',{placeholder:'Tên truyện',maxLength:120});
  var dIn=el('input',{placeholder:'Mô tả ngắn',maxLength:200});
  var cIn=el('input',{placeholder:'Tên chương đầu (VD: Chương 1)',maxLength:120});
  var nIn=el('textarea',{placeholder:'Nội dung chương...'});

  modal.appendChild(el('label',{textContent:'Tên truyện'}));modal.appendChild(tIn);
  modal.appendChild(el('label',{textContent:'Mô tả'}));modal.appendChild(dIn);
  modal.appendChild(el('label',{textContent:'Chương đầu'}));modal.appendChild(cIn);
  modal.appendChild(el('label',{textContent:'Nội dung'}));modal.appendChild(nIn);

  var btns=el('div',{className:'modal-btns'});
  var cancel=el('button',{className:'cancel',textContent:'Hủy'});
  cancel.onclick=function(){bg.remove()};
  var save=el('button',{className:'primary',textContent:'Lưu truyện'});
  save.onclick=function(){
    var t=tIn.value.trim();
    if(!t){alert('Nhập tên truyện đi bro');return}
    var chapTitle=cIn.value.trim()||'Chương 1';
    var chapContent=nIn.value.trim()||'(Chưa có nội dung)';
    var id='user-'+Date.now();
    userStories.push({id:id,title:t,desc:dIn.value.trim()||'Truyện mới',chapters:[{title:chapTitle,content:chapContent}]});
    saveUserStories();
    STORIES=DEFAULT_STORIES.concat(userStories);
    bg.remove();
    render();
  };
  btns.appendChild(cancel);btns.appendChild(save);
  modal.appendChild(btns);
  bg.appendChild(modal);
  bg.onclick=function(e){if(e.target===bg)bg.remove()};
  document.body.appendChild(bg);
}

