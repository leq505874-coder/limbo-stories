// ============ ROUTER ============
function parseHash(){
  var h=location.hash.replace(/^#/,'');
  if(!h)return{page:'home'};
  var p=h.split('/');
  if(p[0]==='story'&&p[1])return{page:'story',storyId:p[1]};
  if(p[0]==='read'&&p[1]&&p[2]!==undefined)return{page:'read',storyId:p[1],chIdx:parseInt(p[2])};
  return{page:'home'};
}

window.addEventListener('hashchange',render);

// ============ RENDER ============
function render(){
  document.querySelectorAll('.controls,.progress').forEach(function(n){n.remove()});
  var route=parseHash();
  var main=document.getElementById('main');
  var title=document.getElementById('pageTitle');
  main.innerHTML='';
  window.scrollTo(0,0);

  if(route.page==='home'){
    title.className='';
    title.innerHTML='Limbo<br>Stories';
    renderHome(main);
  } else if(route.page==='story'){
    var s=STORIES.filter(function(x){return x.id===route.storyId})[0];
    if(!s){location.hash='';return}
    title.className='small';
    title.textContent=s.title;
    renderStory(main,s);
  } else if(route.page==='read'){
    var s2=STORIES.filter(function(x){return x.id===route.storyId})[0];
    if(!s2||!s2.chapters[route.chIdx]){location.hash='';return}
    title.className='small';
    title.textContent=s2.title;
    renderRead(main,s2,route.chIdx);
  }
}

function renderHome(m){
  m.appendChild(el('p',{className:'intro',textContent:'Chọn một truyện để bắt đầu đọc.'}));

  if(isAdmin){
    var addBtn=el('button',{className:'add-story-btn',textContent:'+ Thêm truyện mới'});
    addBtn.onclick=openAddStory;
    m.appendChild(addBtn);
  }

  if(!STORIES.length){
    m.appendChild(el('p',{className:'intro',textContent:'Chưa có truyện nào.'}));
    return;
  }

  STORIES.forEach(function(s){
    var card=el('a',{href:'#story/'+s.id,className:'story-card'});
    card.appendChild(el('h2',{textContent:s.title}));
    card.appendChild(el('p',{textContent:s.desc+' ('+s.chapters.length+' chương)'}));

    if(isAdmin&&!isDefault(s.id)){
      var del=el('button',{className:'delete-story',textContent:'🗑️',title:'Xóa truyện'});
      del.onclick=function(e){
        e.preventDefault();
        e.stopPropagation();
        if(confirm('Xóa truyện "'+s.title+'"?')){
          userStories=userStories.filter(function(x){return x.id!==s.id});
          saveUserStories();
          STORIES=DEFAULT_STORIES.concat(userStories);
          render();
        }
      };
      card.appendChild(del);
    }
    m.appendChild(card);
  });
}

function renderStory(m,s){
  m.appendChild(el('a',{href:'#',className:'back-link',textContent:'← Quay lại'}));
  m.appendChild(el('p',{className:'intro',textContent:s.desc}));

  if(isAdmin&&!isDefault(s.id)){
    var addChap=el('button',{className:'add-story-btn',textContent:'+ Thêm chương'});
    addChap.style.display='inline-flex';
    addChap.onclick=function(){openAddChapter(s)};
    m.appendChild(addChap);
  }

  var list=el('div',{className:'chapter-list'});
  var readUpTo=getProgress(s.id);
  s.chapters.forEach(function(c,i){
    var a=el('a',{href:'#read/'+s.id+'/'+i,className:'chapter-link'+(i<=readUpTo?' read':'')});
    a.appendChild(el('span',{className:'title',textContent:c.title}));
    a.appendChild(el('span',{className:'num',textContent:'Ch.'+(i+1)+' →'}));
    list.appendChild(a);
  });
  m.appendChild(list);
}

function renderRead(m,s,chIdx){
  var ch=s.chapters[chIdx];
  saveProgress(s.id,chIdx);

  var bar=el('div',{className:'progress'});
  document.body.appendChild(bar);

  var reader=el('div',{className:'reader'});
  reader.appendChild(el('a',{href:'#story/'+s.id,className:'back-link',textContent:'← '+s.title}));
  reader.appendChild(el('p',{className:'meta',textContent:'Chương '+(chIdx+1)+' / '+s.chapters.length}));
  reader.appendChild(el('h2',{className:'chapter-title',textContent:ch.title}));
  reader.appendChild(el('div',{className:'content',textContent:ch.content}));

  var nav=el('div',{className:'nav-btns'});
  var prev=el('button',{textContent:'← Chương trước'});
  if(chIdx===0){prev.disabled=true}else{prev.onclick=function(){location.hash='#read/'+s.id+'/'+(chIdx-1)}}
  var next=el('button',{textContent:'Chương sau →'});
  if(chIdx>=s.chapters.length-1){next.disabled=true;next.textContent='Hết truyện'}else{next.onclick=function(){location.hash='#read/'+s.id+'/'+(chIdx+1)}}
  nav.appendChild(prev);nav.appendChild(next);
  reader.appendChild(nav);
  m.appendChild(reader);

  var ctrl=el('div',{className:'controls'});
  var aMinus=el('button',{className:'ctrl-btn',textContent:'A−'});
  var aPlus=el('button',{className:'ctrl-btn',textContent:'A+'});
  var top=el('button',{className:'ctrl-btn',textContent:'↑'});
  aMinus.onclick=function(){fontSize=Math.max(14,fontSize-1);localStorage.setItem('ls:fs',fontSize);applyFont()};
  aPlus.onclick=function(){fontSize=Math.min(28,fontSize+1);localStorage.setItem('ls:fs',fontSize);applyFont()};
  top.onclick=function(){window.scrollTo({top:0,behavior:'smooth'})};
  ctrl.appendChild(aPlus);ctrl.appendChild(aMinus);ctrl.appendChild(top);
  document.body.appendChild(ctrl);

  function onScroll(){
    var h=document.documentElement;
    bar.style.width=(h.scrollTop/(h.scrollHeight-h.clientHeight))*100+'%';
  }
  window.removeEventListener('scroll',window._sh);
  window._sh=onScroll;
  window.addEventListener('scroll',onScroll);
}

